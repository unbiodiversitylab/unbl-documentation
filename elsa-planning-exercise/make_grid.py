#!/usr/bin/env python3
"""Generate the placeholder grid for the ELSA planning exercise.

Writes docs/elsa/exercise/grid.json (without solutions; run solve.R next).
The data is invented: smooth random "landscapes" from a fixed seed, so running
this again gives exactly the same file. Standard library only.

    python elsa-planning-exercise/make_grid.py
    Rscript elsa-planning-exercise/solve.R
"""
from __future__ import annotations

import json
import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "elsa" / "exercise" / "grid.json"
ROWS = COLS = 10
SEED = 20261110


def field(rng: random.Random, bumps: int, spread: tuple[float, float]) -> list[float]:
    """Sum of a few Gaussian bumps at random places, scaled to 0..1."""
    centres = [(rng.uniform(0, ROWS - 1), rng.uniform(0, COLS - 1),
                rng.uniform(*spread), rng.uniform(0.5, 1.0)) for _ in range(bumps)]
    vals = []
    for r in range(ROWS):
        for c in range(COLS):
            vals.append(sum(h * math.exp(-((r - cr) ** 2 + (c - cc) ** 2) / (2 * s * s))
                            for cr, cc, s, h in centres))
    lo, hi = min(vals), max(vals)
    return [(v - lo) / (hi - lo) for v in vals]


def mincost(rng: random.Random) -> dict:
    # Cost: higher towards one corner (near a town), with local noise.
    town = field(rng, 2, (2.5, 4.0))
    cost = [int(round(20 + 160 * t + rng.uniform(-15, 15))) for t in town]
    cost = [max(10, min(200, round(c / 5) * 5)) for c in cost]
    amounts = {}
    for f in ("A", "B", "C"):
        base = field(rng, 3, (1.0, 2.0))
        # Many cells have none of a feature; the rest have 1-50 units.
        amounts[f] = [0 if v < 0.25 else round(50 * v) for v in base]
    targets = {f: round(0.3 * sum(a)) for f, a in amounts.items()}
    return {
        "features": ["A", "B", "C"],
        "targets": targets,
        "shortfallPenalty": 100,
        "bpfOptions": [0, 1, 3, 10],
        "cost": cost,
        "amounts": amounts,
        "solutions": {},
    }


def elsa(rng: random.Random) -> dict:
    # Human footprint: a town in one area, farmland around it, wild land far away.
    foot = field(rng, 2, (2.0, 3.5))
    land = []
    for v in foot:
        land.append("urban" if v > 0.82 else "farmland" if v > 0.5 else
                    "degraded" if v > 0.3 else "intact")
    wild = [1 - v for v in foot]
    bio = field(rng, 3, (1.2, 2.2))
    carbon = field(rng, 2, (1.5, 2.5))
    water = field(rng, 2, (1.0, 1.8))
    values = {
        "biodiversity": [round(10 * (0.6 * b + 0.4 * w), 1) for b, w in zip(bio, wild)],
        "carbon": [round(10 * (0.5 * c + 0.5 * w), 1) for c, w in zip(carbon, wild)],
        "water": [round(10 * v, 1) for v in water],
        "livelihoods": [round(10 * min(1, f * 1.3), 1) for f in foot],
    }
    for k, vals in values.items():  # urban cells contribute nothing
        values[k] = [0 if lc == "urban" else v for v, lc in zip(vals, land)]
    # Existing protected area: the 6 intact cells nearest the wildest cell.
    best = max(range(ROWS * COLS), key=lambda i: wild[i])
    br, bc = divmod(best, COLS)
    pa = sorted(sorted((i for i in range(ROWS * COLS) if land[i] == "intact"),
                       key=lambda i: ((i // COLS - br) ** 2 + (i % COLS - bc) ** 2, i))[:6])
    return {
        "actions": ["protect", "restore", "manage"],
        "features": ["biodiversity", "carbon", "water", "livelihoods"],
        "landClasses": ["intact", "degraded", "farmland", "urban"],
        "eligible": {
            "protect": ["intact", "degraded"],
            "restore": ["degraded", "farmland"],
            "manage": ["farmland", "degraded"],
        },
        # How much of a cell's value an action secures, per feature.
        "contribution": {
            "biodiversity": {"protect": 1.0, "restore": 0.5, "manage": 0.2},
            "carbon": {"protect": 0.8, "restore": 0.8, "manage": 0.3},
            "water": {"protect": 0.6, "restore": 0.6, "manage": 0.5},
            "livelihoods": {"protect": 0.1, "restore": 0.3, "manage": 1.0},
        },
        "landClass": land,
        "protectedArea": pa,
        "values": values,
        "defaults": {
            "limits": {"protect": 20, "restore": 10, "manage": 15},
            "weights": {"biodiversity": 5, "carbon": 5, "water": 5, "livelihoods": 5},
            "lockIn": True,
            "bpf": 0,
        },
        "bpfOptions": [0, 0.5, 1, 2],
        "solutions": [],
    }


def main() -> None:
    rng = random.Random(SEED)
    data = {
        "_about": ("Invented placeholder data for the ELSA planning exercise. Generated by "
                   "elsa-planning-exercise/make_grid.py; best answers added by solve.R. "
                   "Cells are numbered 0-99, row by row from the top left."),
        "source": "placeholder",
        "rows": ROWS,
        "cols": COLS,
        "edgeLength": 10,
        "mincost": mincost(rng),
        "elsa": elsa(rng),
    }
    if OUT.exists():  # keep solutions already computed for identical data
        old = json.loads(OUT.read_text(encoding="utf-8"))
        for k in ("mincost", "elsa"):
            same = {x: y for x, y in old.get(k, {}).items() if x != "solutions"} == \
                   {x: y for x, y in data[k].items() if x != "solutions"}
            if same:
                data[k]["solutions"] = old[k]["solutions"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n",
                   encoding="utf-8")
    m, e = data["mincost"], data["elsa"]
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")
    print("min-cost totals", {f: sum(a) for f, a in m["amounts"].items()}, "targets", m["targets"])
    print("land classes", {c: e["landClass"].count(c) for c in e["landClasses"]},
          "protected area", e["protectedArea"])
    print("eligible cells", {a: sum(lc in e["eligible"][a] for lc in e["landClass"])
                             for a in e["actions"]})


if __name__ == "__main__":
    main()
